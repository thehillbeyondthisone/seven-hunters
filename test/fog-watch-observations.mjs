import assert from 'node:assert/strict';
import { fixture, E, TOWER, ROOM, STATION } from './helpers/morning-fixture.mjs';
import { GALLERY_WATCH_BAYS, galleryBayPosition } from '../src/world/flannan/GalleryStations.js';
import { G } from '../src/core/Globals.js';

const { s, app, place, face, keys, step } = await fixture( false, { search: 'weatherObservationsPreview=33' } );
s.hand.setRest( new E.Vector3( -4.95, TOWER.floor + .74, 3.12 ), .4 );
s.ui.inspection = async ( { onRecord } ) => onRecord();
s.ui.observations = async q => q.complete ? 'chalk' : null;
s.paused = false; s.signal = false; G.night.value = 0;
const w = s.weatherObservations;
place( ROOM.barometer.x, TOWER.floor, ROOM.barometer.z + 1 ); face( ROOM.barometer );
assert.ok( await w.inspect( 'pressure' ) );
place( ROOM.thermometer.x, STATION.yard, ROOM.thermometer.z - 1 ); face( ROOM.thermometer );
assert.ok( await w.inspect( 'temperature' ) );
place( w.windStand.x, STATION.yard, w.windStand.z ); face( s.station.parts.windVane ); assert.ok( w.wind() ); step( .1 );
assert.equal( s.beat, 'd2lookout' );
const bay = galleryBayPosition( GALLERY_WATCH_BAYS[ 0 ], TOWER.deck );
place( bay.x, bay.y, bay.z ); face( new E.Vector3( 500, 0, 100 ) );
keys.add( 'KeyE' ); step( 5 ); keys.delete( 'KeyE' );
assert.equal( w.draft.readings.sea.status, 'fog' );
assert.match( w.draft.readings.sea.label, /not judged/ );
assert.equal( w.draft.readings.sea.source, 'outward lookout; water hidden by fog' );
assert.equal( w.sampler.versions, 0, 'the fog note does not claim a measurement from unseen GPU water' );
face( w.landmarkPosition( 'far' ) ); assert.ok( w.landmark( 'far' ) );
assert.equal( w.draft.landmarks.far.status, 'fog' );
s.save(); const partial = s.loadSave(); s._restore( partial ); s.paused = false;
assert.equal( w.draft.landmarks.far.status, 'fog', 'partial fog observation survives a reload' );
face( w.landmarkPosition( 'near' ) ); assert.ok( w.landmark( 'near' ) );
assert.equal( w.draft.landmarks.near.status, 'fog' );
assert.ok( ! s.flags.identifiedLandmarks?.far && ! s.flags.identifiedLandmarks?.near, 'checked hidden bearings never become identified visible shores' );
assert.ok( w.complete() );
await w.slate(); step( .1 );
assert.equal( s.obs[ 33 ].evidence.readings.sea.status, 'fog' );
assert.equal( s.obs[ 33 ].evidence.landmarks.far.status, 'fog' );
assert.equal( s.beat, 'd2survey', 'honest fog records unlock the safe island outing' );
console.log( 'PASS fog lesson: physical instrument inputs, four-second obscured sea lookout, checked hidden bearings, interrupted save and chalked evidence; no invented visibility.' );
process.exit( 0 );
